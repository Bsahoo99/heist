// Writes components/map/art.gen.ts: the zone art images present in public/art.
// The map reads this static manifest at build time instead of probing for files
// at runtime, so a missing image never causes a 404; the zone falls back to its
// hand-drawn SVG shapes.
import { existsSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

export const ZONE_IDS = [
  "street",
  "shop_window",
  "guard_desk",
  "side_doors",
  "vault",
  "warehouse",
  "across_road",
];

/** Map of zone id to public URL for each `<zone_id>.png` in `dir`, in zone order. */
export function scanArt(dir) {
  const files = existsSync(dir) ? new Set(readdirSync(dir)) : new Set();
  const art = {};
  for (const id of ZONE_IDS) {
    if (files.has(`${id}.png`)) art[id] = `/art/${id}.png`;
  }
  return art;
}

export function renderManifest(art) {
  const lines = Object.entries(art).map(([id, url]) => `  ${id}: ${JSON.stringify(url)},`);
  return [
    "// Generated by scripts/gen-art-manifest.mjs (pnpm gen:art). Do not edit by hand.",
    'import type { Zone } from "@/lib/scene.gen";',
    "",
    "export const ART: Partial<Record<Zone, string>> = {",
    ...lines,
    "};",
    "",
  ].join("\n");
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const webRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
  const out = path.join(webRoot, "components/map/art.gen.ts");
  writeFileSync(out, renderManifest(scanArt(path.join(webRoot, "public/art"))));
  console.log(`wrote ${path.relative(webRoot, out)}`);
}
